FIRST_NAMES = (
    "Aditi", "Ritika", "Neha", "Sanya", "Meher", "Ira", "Kavya", "Tara", "Diya",
    "Ananya", "Pooja", "Isha", "Rhea", "Nisha", "Simran", "Zoya", "Myra", "Anvi",
)
LAST_NAMES = (
    "Sharma", "Verma", "Pillai", "Iyer", "Nair", "Reddy", "Kapoor", "Singh",
    "Joshi", "Mehta", "Bose", "Rao", "Chopra", "Dutta", "Menon", "Gill",
)
BIO_TEMPLATES = {
    "Skincare": ("skincare and affordable routines", "ingredient-first skincare", "acne-safe routines"),
    "Makeup": ("everyday makeup on a budget", "festive looks and dupes", "five-minute makeup"),
    "Haircare": ("haircare science and routines", "curly hair care", "scalp health and growth"),
    "Personal Care": ("body care and grooming basics", "fragrance and body care", "daily grooming"),
}
SUB_NICHES = {
    "Skincare": ["serum", "routine", "brightening", "acne", "sunscreen", "affordable"],
    "Makeup": ["lips", "eyes", "base", "tint", "everyday", "affordable"],
    "Haircare": ["serum", "oil", "frizz", "scalp", "routine"],
    "Personal Care": ["body", "fragrance", "grooming", "daily-use"],
}


def generate_creator_payload(seed: int | None = None) -> dict:
    """A plausible creator profile, as if someone had just filled the form."""
    rng = random.Random(seed)
    niche = rng.choice(CATEGORIES)
    followers = int(10 ** rng.uniform(3.4, 5.6))
    goal = rng.choices(["reach", "revenue", "brand"], weights=[0.35, 0.45, 0.20])[0]

    age_min = rng.choice([18, 18, 20, 22, 25])
    age_max = age_min + rng.choice([6, 8, 10, 12])
    tiers = rng.choice([["T1", "T2"], ["T2", "T3"], ["T1", "T2", "T3"], ["T1"]])

    floor = rng.choice([100, 150, 200, 250, 300])
    ceiling = floor + rng.choice([300, 400, 500, 700, 1000])

    return {
        "name": f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}",
        "followers": followers,
        "niche": niche,
        "goal": goal,
        "price_min": floor,
        "price_max": ceiling,
        "avoid_categories": (
            [rng.choice([c for c in CATEGORIES if c != niche])] if rng.random() < 0.25 else []
        ),
        "audience_age_min": age_min,
        "audience_age_max": age_max,
        "audience_tiers": tiers,
        "sub_niches": rng.sample(SUB_NICHES[niche], k=min(4, len(SUB_NICHES[niche]))),
        "bio": rng.choice(BIO_TEMPLATES[niche]),
        "engagement_rate": round(
            # Smaller accounts engage harder — the usual inverse relationship.
            max(0.012, min(0.11, 0.14 - 0.018 * math.log10(max(followers, 10)) + rng.gauss(0, 0.01))),
            4,
        ),
    }
